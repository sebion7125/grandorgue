#!/usr/bin/env python3
"""Extract Xorcist::SolveBin from xorcist.cpp as a free C function.

clbench compares the OpenCL kernel against the engine's own solver, so
that reference must be the ENGINE'S code and not a copy that quietly
drifts.  Generating it from the source on every build is the only way to
keep that true - a checked-in ref.c would be stale the first time
SolveBin changes.

Usage (from the repository root):
    python3 tools/concealment/make_ref.py > /tmp/ref.c
"""
import pathlib
import re
import sys

SRC = pathlib.Path(__file__).resolve().parents[2] / "src/xorcist/xorcist.cpp"

PROLOGUE = """/* GENERATED by tools/concealment/make_ref.py - do not edit.
 * Xorcist::RhoTest und SolveBin, verbatim, als freie C-Funktionen fuer
 * clbench.  Die beiden Bibliotheks-Statiken, die SolveBin liest, werden
 * zu Globalen: clbench stellt sie und testet damit BEIDE Pfade, den
 * klassischen und den Detektor-Modus. */
#include <math.h>
#include <stdbool.h>
#include <stddef.h>

#ifndef M_PI
#define M_PI 3.14159265358979323846
#endif

double ref_clamp_t = 0.9;   /* RootClampThresh() */
double ref_det_rho = 0.0;   /* s_DetectRho */

"""

# The method's own scratch is sized by AR_ORDER_MAX, a class constant the
# extracted function cannot see; 20 covers every order the kernel builds.
SUBS = [
    # clbench's reference is the Durand-Kerner path; the Schur branch
    # references library statics the extracted function cannot see.
    (r"  if \(s_UseSchur[^&]*?\n  \}\n\n", ""),
    (r"void Xorcist::SolveBin\(\s*const (double|float) \*pP, const \1 \*pQ, "
     r"unsigned order, float \*pCoefRe,\s*float \*pCoefIm, float \*pRootRe, "
     r"float \*pRootIm\) \{",
     lambda m: (
         "void ref_solve(\n"
         "  const %s *pP, const %s *pQ, unsigned order, unsigned NUnused,\n"
         "  float *pCoefRe, float *pCoefIm, float *pRootRe, float *pRootIm) "
         "{\n  (void)NUnused;" % (m.group(1), m.group(1)))),
    (r"const unsigned N = AR_ORDER_MAX;", "const unsigned N = order;"),
    (r"std::swap\(m\[c\]\[j\], m\[piv\]\[j\]\);",
     "{ double t_ = m[c][j]; m[c][j] = m[piv][j]; m[piv][j] = t_; }"),
    (r"std::isfinite", "isfinite"),
    (r"std::max", "fmax"),
    (r"std::min", "fmin"),
    # The clamp threshold reads a library static the extracted function
    # cannot see; clbench sets it through the global instead, so both
    # the classic and the detector path are testable.
    (r"const double clampT = RootClampThresh\(\);",
     "const double clampT = ref_clamp_t;"),
    # Der Detektor-Modus liest ebenfalls eine Bibliotheks-Statik.
    (r"const double det = \(double\)s_DetectRho\.load\("
     r"std::memory_order_relaxed\);",
     "const double det = ref_det_rho;"),
    # Reine Diagnose ohne Verhaltensaenderung - haengt an Zaehl-Atomics,
    # die es ausserhalb der Klasse nicht gibt.
    (r"  // Messung ohne Verhaltensaenderung.*?\n  \}\n", "", re.S),
    (r"AR_ORDER_MAX", "20"),
]


def main() -> int:
    src = SRC.read_text()
    # RhoTest zuerst: SolveBin ruft ihn im Detektor-Modus auf, und der
    # Kernel hat seit dem 07.08. seine eigene Portierung davon - genau
    # deshalb muss er mitverglichen werden.
    rstart = src.index("  static bool RhoTest(")
    rend = src.index("\n  }\n", rstart) + 4
    # NICHT static: clbench zaehlt damit selbst, wie viele Bins den Test
    # bestehen - die Zahl ist der ganze Grund fuer den Modus.
    rho = src[rstart:rend].replace(
        "static bool RhoTest(", "bool ref_rho_test(")
    start = src.index("void Xorcist::SolveBin(")
    tail = src.index("pCoefIm[k] = (float)(-ci[k + 1]);", start)
    end = src.index("\n}\n", tail) + 3
    body = rho + "\n" + src[start:end]
    body = body.replace("RhoTest(ar, ai", "ref_rho_test(ar, ai")
    for sub in SUBS:
        pattern, repl = sub[0], sub[1]
        flags = sub[2] if len(sub) > 2 else 0
        body = re.sub(pattern, repl, body, flags=flags)
    if "Xorcist::" in body:
        sys.stderr.write("make_ref: unhandled Xorcist:: reference left in\n")
        return 1
    sys.stdout.write(PROLOGUE + body)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
