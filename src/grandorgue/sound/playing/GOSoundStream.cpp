CacheT &GOSoundStream::GetCache() {
  if constexpr (std::is_same_v<CacheT, GOSoundCompressionCache>)
    return cache;
  else if constexpr (std::is_same_v<CacheT, GOSoundCompressionCacheV3>)
    return cacheV3;
  else {
    static_assert(
      std::is_same_v<CacheT, GOSoundCompressionCache>
        || std::is_same_v<CacheT, GOSoundCompressionCacheV3>,
      "unsupported cache type");
  }
}

