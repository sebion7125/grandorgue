void GOSoundStream::GetHistory(
  int history[BLOCK_HISTORY][MAX_OUTPUT_CHANNELS]) const {
  uint8_t nChannels = audio_section->GetChannels();

  memset(
    history, 0, sizeof(history[0][0]) * BLOCK_HISTORY * MAX_OUTPUT_CHANNELS);

  /* Seqlock read side - now covering the WHOLE field set the branches
   * below read, not just cacheV3: a render worker's segment switch
   * (GoToStartSegment) rewrites pos-vs-transition_position, end_ptr, ptr
   * and the caches as one ensemble, and a copy torn across it indexes the
   * tiny end-segment buffer thousands of samples out of bounds (all three
   * wind-down crashes had exactly that signature). pos itself still
   * advances sample-by-sample without a bump - harmless: a few samples of
   * drift stay inside the end segment's read-ahead reserve; only the
   * SEGMENT SWITCH tears dangerously, and that is fenced. */
  unsigned pos = 0, transitionC = 0;
  const unsigned char *endPtrC = nullptr, *ptrC = nullptr;
  GOSoundCompressionCacheV3 tmpV3;
  GOSoundCompressionCache tmpLegacy;
  bool consistent = false;

  for (unsigned tries = 0; tries < 20000 && !consistent; tries++) {
    const uint16_t s1 = cacheV3.m_seq.load(std::memory_order_acquire);

    if (s1 & 1) {
      GOSpinPause();
      continue;
    }
    pos = m_ResamplingPos.GetIndex();
    transitionC = transition_position;
    endPtrC = end_ptr;
    ptrC = ptr;
    tmpV3 = cacheV3;
    tmpLegacy = cache;
    std::atomic_thread_fence(std::memory_order_acquire);
    consistent = cacheV3.m_seq.load(std::memory_order_relaxed) == s1
      /* The batch decoder mutates lanes WITHOUT bumping the sequence (a
       * bump per lane per call cost ~4% voice time - measured 17.07, the
       * fifth per-sample-atomic lesson). Instead the READER validates the
       * copy: a snapshot torn across a batch block refresh shows an
       * impossible width/remaining pair; retry then. Torn PREDICTOR values
       * alone stay possible and merely yield a slightly wrong history
       * (inaudible), never a wild pointer - those two fields bound every
       * address this copy can compute. */
      && tmpV3.m_curWidth <= 4 && tmpV3.m_blockRemaining <= 1024
      && (tmpV3.m_blockRemaining == 0 || tmpV3.m_curWidth >= 1);
    if (!consistent)
      GOSpinPause();
  }
  if (!consistent)
    return; // history stays zeroed - see the fallback rationale above

  if (pos >= transitionC)
    for (unsigned i = 0; i < BLOCK_HISTORY; i++)
      for (uint8_t j = 0; j < nChannels; j++)
        /* end_ptr is a VIRTUAL pointer (end_data - transition*frame, see
         * GOSoundAudioSection.cpp) and must be indexed with the ABSOLUTE
         * position - exactly like the end-block decoder does. The old
         * `pos - transition + i` subtracted transition TWICE, reading
         * ~2*transition frames BEFORE the end buffer: silently wrong
         * history since the resampler rework (#1919, upstream too), and a
         * hard crash whenever end_data-transition*frame leaves the
         * mapping - every 'silent wind-down death' dump decoded to this
         * one line. Found via the crash reporter, 2026-07-16. */
        history[i][j] = audio_section->GetSampleData(endPtrC, pos + i, j);
  else if (!audio_section->IsCompressed())
    for (unsigned i = 0; i < BLOCK_HISTORY; i++)
      for (uint8_t j = 0; j < nChannels; j++)
        history[i][j] = audio_section->GetSampleData(ptrC, pos + i, j);
  else if (audio_section->GetCompressionCodec()
    == GOSoundAudioSectionCompressionCodec::V3) {
    // Copies were taken consistently under the protocol above.
    for (unsigned i = 0; i < BLOCK_HISTORY; i++) {
      for (uint8_t j = 0; j < nChannels; j++)
        history[i][j] = tmpV3.m_value[j];
      tmpV3.DecompressionStep(nChannels);
    }
  } else {
    for (unsigned i = 0; i < BLOCK_HISTORY; i++) {
      for (uint8_t j = 0; j < nChannels; j++)
        history[i][j] = tmpLegacy.m_value[j];
      tmpLegacy.DecompressionStep(
        nChannels, audio_section->GetBitsPerSample() >= 20);
    }
  }
}


